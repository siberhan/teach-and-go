// Writes src/captures.ts: frame lists and marks of every filmed phase, for the Phone component.
import fs from 'node:fs'
const dir = new URL('../public/cap/', import.meta.url)
const out = {}
const marks = {}
for (const phase of fs.readdirSync(dir)) {
  const f = new URL(phase + '/index.json', dir)
  if (!fs.existsSync(f)) continue
  const d = JSON.parse(fs.readFileSync(f, 'utf8'))
  out[phase] = d.frames
  marks[phase] = Object.fromEntries(d.marks.map((m) => [m.name, m.t]))
}
fs.writeFileSync(new URL('../src/captures.ts', import.meta.url), `// Generated by capture/index-captures.mjs\nexport const captures: Record<string, { file: string; t: number }[]> = ${JSON.stringify(out)}\nexport const marks: Record<string, Record<string, number>> = ${JSON.stringify(marks, null, 1)}\n`)
console.log(Object.keys(out), marks)
